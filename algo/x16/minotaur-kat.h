/* Known-answer test for minotaur (Ring / RNG).
 *
 * Anchored on Ring's genesis header from its chainparams.cpp. sha256d of
 * this header reproduces the GENESIS_HASH that chainparams asserts, which
 * proves the serialization; Ring keeps block hash and PoW hash separate, so
 * no published id can supply the expected digest. The digest is therefore
 * checked against this block's own nBits target as well as byte-compared.
 *
 * The digest came from this implementation, so this is a regression and
 * mis-built-binary gate rather than an independent consensus proof: the same
 * vector must hold on the AES and sph_* paths, which is what catches a build
 * with the crypto extensions compiled out. Genesis has a null prevhash, so
 * it cannot catch a wrong prevhash offset. */

typedef struct
{
   const char    *name;
   unsigned char  header[80];
   unsigned char  digest[32];   /* byte order minotaur_hash emits */
   unsigned char  target[32];   /* this block's nBits, little-endian */
} minotaur_kat_t;


