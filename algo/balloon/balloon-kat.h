/* Known-answer vectors for balloon. Every one is checked at startup and a
 * mismatch is fatal: this hash has no cheap way to notice a wrong digest at
 * runtime, so a silent consensus break would show up only as rejected shares.
 *
 * Three independent layers, so a failure says *where*:
 *
 *   1. AES-128, against FIPS-197 C.1. The cipher is the only novel primitive
 *      in the port and the only place a keying or endianness mistake hides.
 *   2. The index bitstream, against the key and keystream OpenSSL produces
 *      for the same salt. Covers the SHA-256 key derivation, the 16-of-32
 *      key bytes and the CTR counter convention across a block boundary.
 *   3. The construction, five headers deep.
 *
 * Provenance of layer 3, which is what makes these worth trusting:
 *
 *   synthetic 0..3   header[i] = (i*7 + 1 + trial*31) & 0xff. The digests come
 *                    from an independent implementation, compiled unmodified
 *                    and run as a differential oracle — specifically the path
 *                    that implementation re-hashes its own candidate shares
 *                    with, rather than either of its faster ones.
 *
 *   live work unit   A real work unit from mainnet block 4450499, whose share
 *                    a pool accepted. It pins what no synthetic vector can:
 *                    the 80-byte header assembly, the big-endian-word
 *                    convention, s_cost=128 / t_cost=4 against the live chain,
 *                    and the salt being header bytes 0..31 of *that* layout.
 *
 *                    Its digest meets the difficulty the share was accepted
 *                    at: word[7] (bytes 28..31, little-endian) is 0x000019b4
 *                    against a limit of 0x2710. A construction wrong in any
 *                    respect lands under that with probability ~1/434000, so
 *                    the acceptance is the proof and the digest is only the
 *                    artefact.
 *
 *                    The winning nonce, 128454, also fixes opt_target_factor:
 *                    at factor 1 the expected count is 429497 (so this is the
 *                    26th percentile), while factor 256 would predict 1678.
 *                    Factors 256 and 65536 are therefore excluded.         */

