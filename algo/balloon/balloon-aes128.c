/* Multiply by x in GF(2^8), branch-free (the shift keeps it constant-time-ish;
 * this is a public keystream, so that is a habit, not a requirement).        */
static inline uint8_t xtime( uint8_t x )
{
   return (uint8_t)( ( x << 1 ) ^ ( ( x >> 7 ) * 0x1b ) );
}

void balloon_aes128_init( balloon_aes128_ctx *ctx, const uint8_t key[16] )
{
   memcpy( ctx->rk[0], key, 16 );

   uint8_t rcon = 0x01;
   for ( int r = 1; r <= BALLOON_AES128_ROUNDS; r++ )
   {
      const uint8_t *prev = ctx->rk[r-1];
      uint8_t       *cur  = ctx->rk[r];

      /* w[4r] = w[4r-4] ^ SubWord(RotWord(w[4r-1])) ^ Rcon[r] */
      cur[0] = prev[0] ^ SBOX[ prev[13] ] ^ rcon;
      cur[1] = prev[1] ^ SBOX[ prev[14] ];
      cur[2] = prev[2] ^ SBOX[ prev[15] ];
      cur[3] = prev[3] ^ SBOX[ prev[12] ];
      for ( int i = 4; i < 16; i++ )
         cur[i] = prev[i] ^ cur[i-4];

      rcon = xtime( rcon );
   }
}

void balloon_aes128_encrypt_block( const balloon_aes128_ctx *ctx,
                                   const uint8_t in[16], uint8_t out[16] )
{
   uint8_t s[16], t[16];

   for ( int i = 0; i < 16; i++ ) s[i] = in[i] ^ ctx->rk[0][i];

   for ( int round = 1; round < BALLOON_AES128_ROUNDS; round++ )
   {
      /* SubBytes + ShiftRows: row r rotates left by r columns. */
      for ( int c = 0; c < 4; c++ )
         for ( int r = 0; r < 4; r++ )
            t[ r + 4*c ] = SBOX[ s[ r + 4*( ( c + r ) & 3 ) ] ];

      /* MixColumns + AddRoundKey.
       * b0 = 2a0^3a1^a2^a3 = a0 ^ (a0^a1^a2^a3) ^ xtime(a0^a1), and rotations. */
      const uint8_t *rk = ctx->rk[round];
      for ( int c = 0; c < 4; c++ )
      {
         const uint8_t a0 = t[4*c], a1 = t[4*c+1], a2 = t[4*c+2], a3 = t[4*c+3];
         const uint8_t x  = a0 ^ a1 ^ a2 ^ a3;
         s[4*c+0] = a0 ^ x ^ xtime( a0 ^ a1 ) ^ rk[4*c+0];
         s[4*c+1] = a1 ^ x ^ xtime( a1 ^ a2 ) ^ rk[4*c+1];
         s[4*c+2] = a2 ^ x ^ xtime( a2 ^ a3 ) ^ rk[4*c+2];
         s[4*c+3] = a3 ^ x ^ xtime( a3 ^ a0 ) ^ rk[4*c+3];
      }
   }

   /* Final round: no MixColumns. */
   const uint8_t *rk = ctx->rk[ BALLOON_AES128_ROUNDS ];
   for ( int c = 0; c < 4; c++ )
      for ( int r = 0; r < 4; r++ )
         out[ r + 4*c ] = SBOX[ s[ r + 4*( ( c + r ) & 3 ) ] ] ^ rk[ r + 4*c ];
}

void balloon_aes128_keystream( const balloon_aes128_ctx *ctx, uint64_t counter,
                               uint8_t *out, size_t outlen )
{
   /* Counter block is BE128(counter). Balloon starts at 0 and needs ~25.6k
    * blocks, so the high half is always zero here, but carry into it is
    * implemented anyway rather than leaving a 2^64 landmine.                 */
   uint8_t ctr[16] = { 0 };
   uint8_t block[16];

   for ( int i = 0; i < 8; i++ )
      ctr[15-i] = (uint8_t)( counter >> ( 8*i ) );

   while ( outlen )
   {
      balloon_aes128_encrypt_block( ctx, ctr, block );

      const size_t n = outlen < 16 ? outlen : 16;
      memcpy( out, block, n );
      out    += n;
      outlen -= n;

      for ( int i = 15; i >= 0; i-- )
         if ( ++ctr[i] ) break;
   }
}
