/* megabtx (BitCore, BTX) known-answer vectors -- real chain data.
 *
 * Five mainnet headers, all mined after the fork at HASH_FORK_TIME_1 =
 * 1598961600, each checked two ways:
 *
 *   1. sha256d( header ) reproduces the published block id, proving the header
 *      reconstruction independently of the PoW function;
 *   2. the digest lands under the header's own nBits target, which a wrong
 *      construction clears with probability ~2^-37 per block.
 *
 * digest[] is generated, not published -- the chain only proves the <= target
 * relation. Assert both: the digest catches any deviation immediately, the
 * target ties it to consensus.
 *
 * The five nTimes give five distinct slot orders. Block 800000 predates
 * upstream ee07eac6 ("Merge hash func permutation arrays into one variable"),
 * so it also covers the pre-refactor code shape Megacoin's mega-mec.h still
 * uses -- which is what lets BTX chain data settle megamec's uninitialised
 * slot-0 question too.
 *
 * header[] is the wire header, i.e. what scanhash passes on after its bswap
 * pass. target[] is nBits as an internal little-endian uint256.
 */

#define MEGABTX_NUM_KATS 5

struct megabtx_kat
{
   const char    *name;
   unsigned char  header[80];
   unsigned char  digest[32];
   unsigned char  target[32];
};

